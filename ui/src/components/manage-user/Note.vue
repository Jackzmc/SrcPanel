<template>
<div class="list-item">
  <div class="list-item-content">
    <div class="list-item-title">
      <template v-if="edit">
        <label class="label">Marked By:</label>
        <input v-model="edit.markedBy" type="text" class="input" style="width:50%" />
      </template>
      <span v-else>
        <router-link :to="routeHref">
          {{ note.markedBy.name }}:
        </router-link>
        <span class="ml-2 has-text-grey-light is-inline subtitle is-6">{{ note.markedBy.id }}</span>
        <span class="tag is-pulled-right is-info">#{{ note.id }}</span>
      </span>
    </div>
    <div class="list-item-description has-text-black">
      <template v-if="edit">
        <label class="label">Content:</label>
        <input v-model="edit.content" type="text" class="input" />
      </template>
      <template v-else>
        <span :class="note.content.startsWith('@') ? 'tag is-dark' : ''" :data-tooltip="note.content.startsWith('@') ? 'Is an automatic action' : undefined">
          {{ note.content }}
        </span>
        <em v-if="isRep" class="is-6 ml-2 has-text-grey-light" data-tooltip="Created from /rep or thumbs up/down rating system">
          (autogenerated)
          <Icon icon="fa-question-circle" icon-class="has-text-info" />
        </em>
      </template>
    </div>
  </div>

  <div class="list-item-controls">
    <div class="buttons is-right">
      <!-- <button :class="['button', {'is-info': entry.showDetails, 'is-outlined': entry.showDetails }]">
        <span @click="entry.showDetails = !entry.showDetails">Details</span>
      </button> -->
      <span v-if="edit">
        <button class="button is-inverted is-success has-tooltip-success" data-tooltip="Save changes" @click="saveNote">
          <Icon icon-class="is-small" icon="check" />
        </button>
        <button class="button is-inverted is-black" data-tooltip="Discard changes" @click="edit = undefined">
          <Icon icon-class="is-small" icon="times" />
        </button>
        <button class="button  is-inverted is-danger has-tooltip-danger" data-tooltip="Delete note" @click="deleteNote">
          <Icon icon-class="is-small" icon="trash" />
        </button>
      </span>
      <template v-else>
        <button v-if="canEdit" class="button is-inverted is-outlined is-black" @click="startEdit">
          <Icon icon-class="is-small has-text-black" icon="edit" />
        </button>
      </template>
    </div>
  </div>
</div>
</template>

<script setup lang="ts">
import { notify } from '@kyvg/vue3-notification';
import { ref, computed } from 'vue';
import { Note } from '../../../../common-types/Note.js'
import { PrivilegedUser } from '../../js/User';
import { useRoute } from 'vue-router';
const route = useRoute()
const emit = defineEmits(["deleted", "change"])
const props = defineProps<{
  note: Note,
  privUser: PrivilegedUser
}>()

interface EditedNote {
  content: string,
  markedBy: string
}

const canEdit = computed(() => {
  return props.privUser.hasPermission("notes.edit", props.note.markedBy.id)
})

const routeHref = computed(() => {
  if(props.note.markedBy.id === props.note.client.id) return '#'
  return { name: 'manage-user', params: { id: props.note.markedBy.id }, query: { returnTo: route.fullPath }}
})

const isRep = computed(() => {
  return props.note.content === "+rep" || props.note.content === "-rep"
})

let edit = ref<EditedNote>()
let loading = ref(false)

function startEdit() {
  edit.value = {
    content: props.note.content,
    markedBy: props.note.markedBy.id
  }
}

async function saveNote() {
  if(!edit.value) return console.error("saveNote called when not in edit mode")
  loading.value = true
  try {
      const response = await fetch(`/api/notes/${props.note.id}`, {
          method: 'PUT',
          headers: {
              'Content-Type': 'application/json'
          },
          body: JSON.stringify(edit.value)
      })
      if(response.ok) {
          notify({
              type: "success",
              text: `Edited note #${props.note.id}`
          })
          emit('change', { id: props.note.id, content: edit.value.content, markedBy: edit.value.markedBy })
          edit.value = undefined
      } else {
          const json = await response.json()
          notify({
              type: "error",
              title: `Failed to edit note #${props.note.id}`,
              text: json.message
          })
      }
  } catch(err: any) {
      console.error(err)
      notify({
          type: "error",
          title: `Failed to edit note #${props.note.id}`,
          text: err.message
      })
  } finally {
    loading.value = false
  }
}
async function deleteNote() {
    if(window.confirm("Are you sure you want to delete this note?")) {
      loading.value = true
        try {
            const response = await fetch(`/api/notes/${props.note.id}`, { method: 'DELETE' })
            if(response.ok) {
                notify({
                    type: "success",
                    text: `Deleted note #${props.note.id}`
                })
                emit("deleted")
            } else {
                const json = await response.json()
                notify({
                    type: "error",
                    title: `Failed to delete note #${props.note.id}`,
                    text: json.message
                })
            }
        } catch(err: any) {
            notify({
                type: "error",
                title: `Failed to delete note #${props.note.id}`,
                text: err.message
            })
        } finally {
          loading.value = false
        }
    }
}
</script>
